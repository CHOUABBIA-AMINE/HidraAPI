package dz.sh.hidra.modules.party.infrastructure.persistence.entity;

import dz.sh.hidra.modules.party.domain.value.*;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.time.Instant;

    /**
     * Database-backed JPA entity for PartyRole.
     */
    @Entity
    @Table(name = "hidra_party_role")
    public class PartyRoleJpaEntity {

        @Id
    @Column(name = "id", nullable = false, length = 80)
    private String id;

    @Column(name = "code", nullable = false, length = 120)
    private String code;

    @Column(name = "description", nullable = true, columnDefinition = "text")
    private String description;

    @Column(name = "qualification_required_by_default", nullable = false)
    private boolean qualificationRequiredByDefault;

    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false, length = 40)
    private PartyCatalogStatus status;

    @Column(name = "created_at", nullable = false)
    private Instant createdAt;

    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

        protected PartyRoleJpaEntity() {
            // Required by JPA.
        }

        public PartyRoleJpaEntity(
                String id,
            String code,
            String description,
            boolean qualificationRequiredByDefault,
            PartyCatalogStatus status,
            Instant createdAt,
            Instant updatedAt
        ) {
            this.id = id;
        this.code = code;
        this.description = description;
        this.qualificationRequiredByDefault = qualificationRequiredByDefault;
        this.status = status;
        this.createdAt = createdAt;
        this.updatedAt = updatedAt;
        }


    public String id() {
        return id;
    }


    public String code() {
        return code;
    }


    public String description() {
        return description;
    }


    public boolean qualificationRequiredByDefault() {
        return qualificationRequiredByDefault;
    }


    public PartyCatalogStatus status() {
        return status;
    }


    public Instant createdAt() {
        return createdAt;
    }


    public Instant updatedAt() {
        return updatedAt;
    }

    }
